from __future__ import annotations
import refagent.utils.project_manager as pm
import refagent.refactoring_types.refactorings as refactoring_types
import refagent.benchmark.creation.add_gh_comments as gh_comment
from pydantic import BaseModel, Field
from typing import List, Optional, Type


class BenchmarkItem(BaseModel):
    ref_id: int
    project_name: str
    v1_hash: str
    v2_hash: str
    orig_commit_message: str = Field(
        ..., description="original commit message from the developer"
    )
    improved_commit_message: str = (
        Field(..., description="improved commit message from LLM"),
    )
    change_summary: str = (
        Field(..., description="summary of the changes - LLM generated"),
    )
    hints: List[str] = (Field(..., description="A list of hints generated by LLM"),)
    starting_file: str
    refactoring_changes: List[refactoring_types.RefminerOut]
    diffs: List[pm.MyDiff]
    pull_request: Optional[gh_comment.GithubPR] = None

    class Config:
        arbitrary_types_allowed = True

    @classmethod
    def load(cls, _json, load_changes=False) -> "BenchmarkItem":
        try:
            if load_changes:
                changes = pm.EvalProject(_json["project"]).get_changes(_json["v2_hash"])
            else:
                changes = []
        except:
            changes = []
        return cls(
            ref_id=_json["id"],
            project_name=_json["project"],
            v1_hash=_json["v1_hash"],
            v2_hash=_json["v2_hash"],
            orig_commit_message=_json["orig_commit_message"],
            improved_commit_message=_json["improved_commit_message"],
            change_summary=_json["change_summary"],
            hints=_json["hints"],
            starting_file=_json["starting_file"],
            refactoring_changes=refactoring_types.RefminerOut.load_from_json(
                _json["refactoring_changes"]
            ),
            diffs=changes,
            pull_request=(
                gh_comment.GithubPR(**_json["pull_request"])
                if _json.get("pull_request")
                else None
            ),
        )

    def to_json(self):
        return {
            "id": self.ref_id,
            "project": self.project_name,
            "v1_hash": self.v1_hash,
            "v2_hash": self.v2_hash,
            "orig_commit_message": self.orig_commit_message,
            "improved_commit_message": self.improved_commit_message,
            "change_summary": self.change_summary,
            "hints": self.hints,
            "starting_file": self.starting_file,
            "refactoring_changes": [
                c.model_dump(mode="json") for c in self.refactoring_changes
            ],
            "diffs": [d.to_json() for d in self.diffs],
        }


class RenameItem(BenchmarkItem):
    corename_id: Optional[int] = None
    seed_hash: Optional[str] = None
    seed_example: Optional[refactoring_types.RefminerOut] = None

    def to_json(self):
        json_ = super().to_json()
        json_["corename_id"] = self.corename_id
        json_["seed_hash"] = self.seed_hash
        json_["seed_example"] = (
            self.seed_example.model_dump() if self.seed_example else None
        )
        return json_

    @classmethod
    def load(cls, _json) -> "RenameItem":
        return cls(
            ref_id=_json["id"],
            project_name=_json["project"],
            v1_hash=_json["v1_hash"],
            v2_hash=_json["v2_hash"],
            orig_commit_message=_json["orig_commit_message"],
            improved_commit_message=_json["improved_commit_message"],
            change_summary=_json["change_summary"],
            hints=_json["hints"],
            starting_file=_json["starting_file"],
            refactoring_changes=refactoring_types.RefminerOut.load_from_json(
                _json["refactoring_changes"]
            ),
            diffs=[],
            pull_request=(
                gh_comment.GithubPR(**_json["pull_request"])
                if _json.get("pull_request")
                else None
            ),
            corename_id=(
                _json["corename_id"] if _json.get("corename_id") is not None else None
            ),
            seed_hash=_json["seed_hash"] if _json.get("seed_hash") else None,
            seed_example=(
                refactoring_types.RefminerOut.load_from_dictionary(
                    _json["seed_example"]
                )
                if _json.get("seed_example")
                else None
            ),
        )


def load_benchmark(
    json_benchmark, bench_type: Type[BenchmarkItem] = BenchmarkItem
) -> list[BenchmarkItem]:
    return [bench_type.load(i) for i in json_benchmark]
